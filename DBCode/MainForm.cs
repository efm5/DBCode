      public MainForm() {
         mForm = this;
         Opacity = 0;
         InitializeUI();
         mThisWindow = Handle;
         int wantedWidth = MinimumMainBottomWidth() + 20;
         if (mUiState.mFirstLaunch) {
            mUiState.FormBounds = new Rectangle(new Point(1, 1), new Size(wantedWidth, 300));
            mForm.Bounds = mUiState.FormBounds;
            EnsureWindowFitsMonitor(this);
            CenterFormOnMonitor(this);
            mUiState.FormBounds = mForm.Bounds;
            mUiState.mFirstLaunch = false;
         }
         MinimumSize = new Size(wantedWidth, 150);
         Assembly assembly = Assembly.GetExecutingAssembly();
         FileVersionInfo? fileVersionInfo = FileVersionInfo.GetVersionInfo(assembly.Location);
         if (fileVersionInfo == null)
            mVersionString = "0.0.0.2";
         else {
            if (fileVersionInfo.FileVersion == null)
               mVersionString = "0.0.0.2";
            else {
               mVersionString = fileVersionInfo.FileVersion;
               if (mVersionString == null)
                  mVersionString = "0.0.0.2";
            }
         }
         mVersionLabel?.Text = "v: " + mVersionString;
         mCurrentViewMode = ViewMode.Features;
         mIsTargetingEnabled = false;
         mTargetWindowName = string.Empty;
         mPreMinimalText = Text;
         mPreMinimalControlBox = ControlBox;
         TargetListManager.EnsureDataFiles();
      }

